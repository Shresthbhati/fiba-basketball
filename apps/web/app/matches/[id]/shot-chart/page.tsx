export default function MatchShotChartPage({ params }: { params: Promise<{ id: string }> }) {
  const { id } = use(params);

  const { data: fetchedData } = useQuery<ShotChartData>({
    queryKey: ["shot-chart", id],
    queryFn: () => api<ShotChartData>(`/matches/${id}/shot-chart`),
    enabled: !!id && id !== "match-demo-01",
    retry: false,
  });

  const data = fetchedData || SAMPLE_SHOT_CHART_DATA;

  return (
    <div style={{ maxWidth: 1040, margin: "0 auto", padding: "24px 16px" }}>
      <div style={{ marginBottom: 16 }}>
        <Link href={`/score/${id}`} style={{ fontSize: 13, color: "var(--muted-foreground)" }}>
          ← Back to Live Match Scoring
        </Link>
      </div>

      <ShotChartView
        data={data}
        homeTeamName="Warriors"
        awayTeamName="Hawks"
      />
    </div>
  );
}
